// Generates supabase/seed.sql from the in-app catalogue so the database and the app
// ship the same original demo content. Run: npm run db:seed-sql
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jiti = createJiti(import.meta.url, { alias: { "@": path.join(root, "src") } });
const { CATALOG, CATEGORIES } = await jiti.import(path.join(root, "src/lib/content/catalog.ts"));

const q = (v) => (v === undefined || v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

const lines = ["-- Generated by scripts/generate-seed.mjs. Original demo content written for Calm Companion.", ""];
CATEGORIES.forEach((c, i) => {
  lines.push(
    `insert into public.content_categories (id, name, kind, description, artwork, sort_order) values (${q(c.id)}, ${q(c.name)}, ${q(c.kind)}, ${q(c.description)}, ${json(c.artwork)}, ${i}) on conflict (id) do update set name = excluded.name, description = excluded.description, artwork = excluded.artwork, sort_order = excluded.sort_order;`,
  );
});
lines.push("");
for (const c of CATALOG) {
  lines.push(
    `insert into public.content_items (id, kind, title, subtitle, description, narrator, category_ids, tags, needs, artwork, script, ambience_preset_id, source, featured, fixed_minutes) values (${q(c.id)}, ${q(c.kind)}, ${q(c.title)}, ${q(c.subtitle)}, ${q(c.description)}, ${q(c.narrator)}, ${arr(c.categoryIds)}, ${arr(c.tags)}, ${arr(c.needs)}, ${json(c.artwork)}, ${json(c.script)}, ${q(c.ambiencePresetId)}, ${q(c.source)}, ${c.featured ? "true" : "false"}, ${c.fixedMinutes ?? "null"}) on conflict (id) do update set title = excluded.title, subtitle = excluded.subtitle, description = excluded.description, script = excluded.script, artwork = excluded.artwork, tags = excluded.tags;`,
  );
}
writeFileSync(path.join(root, "supabase/seed.sql"), lines.join("\n") + "\n");
console.log(`Wrote ${CATEGORIES.length} categories and ${CATALOG.length} items to supabase/seed.sql`);
